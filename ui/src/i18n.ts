import { createRoot, createSignal } from 'solid-js';

export type Lang = 'ru' | 'en';
/** What the user picked in Settings: a language or "follow Windows". */
export type LangPref = 'system' | Lang;

const fromTag = (tag: string | undefined): Lang => (/^ru\b/i.test(tag ?? '') ? 'ru' : 'en');

const state = createRoot(() => {
  const [lang, setLang] = createSignal<Lang>(fromTag(typeof navigator !== 'undefined' ? navigator.language : undefined));
  return { lang, setLang };
});

export const lang = state.lang;

/** `system` = the Windows display language reported by the core (or the WebView's, in the browser preview). */
export function applyLang(pref: string | undefined, system: string | undefined) {
  const l: Lang = pref === 'ru' || pref === 'en' ? pref : fromTag(system ?? navigator.language);
  state.setLang(l);
  document.documentElement.lang = l;
}

/** Locale for Intl formatters. en-GB: 24-hour clock and day-month order, like the Monday-based grid. */
export const locale = () => (lang() === 'en' ? 'en-GB' : 'ru-RU');

/** Russian plural forms: one (1, 21, …), few (2–4, 22–24, …), many (0, 5–20, …). */
export function pluralRu(n: number, one: string, few: string, many: string): string {
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
  return many;
}
const pl = (n: number, one: string, many: string) => (n === 1 ? one : many);

